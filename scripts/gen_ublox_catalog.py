"""Regenerate frontend/src/utils/ubloxCatalog.ts from the u-blox Interface Descriptions.

    uv run python scripts/gen_ublox_catalog.py

Needs `pdftotext` (poppler) and the documents in refs/u-blox/ (not in the
repository). Reads the configuration items (name, key ID, type) of the
ZED-F9P (F9 HPG 1.51) and NEO-D9C (D9 QZS 1.01): the message output rates
per port (CFG-MSGOUT), and the items the Receiver tab reads and presets set
(CFG-RATE, CFG-SIGNAL, CFG-*OUTPROT, CFG-QZSS).

A message's five output keys are consecutive from its I2C key: I2C, UART1,
UART2, USB, SPI (checked over every message listed whole); some names are
cut by the PDF layout, so the ports come from that rule.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = {
    "ZED-F9P": "u-blox-F9-HPG-1.51_InterfaceDescription_UBXDOC-963802114-13124.pdf",
    "NEO-D9C": "u-blox-D9-QZS-1.01_InterfaceDescription_UBX-21031777.pdf",
}
OUT = ROOT / "frontend/src/utils/ubloxCatalog.ts"
PORT_OFFSET = {"I2C": 0, "UART1": 1, "UART2": 2, "USB": 3, "SPI": 4}
OTHER_GROUPS = ("RATE", "SIGNAL", "USBOUTPROT", "UART1OUTPROT", "UART2OUTPROT", "I2COUTPROT", "SPIOUTPROT", "QZSS")
ITEM = re.compile(
    r"(CFG-[A-Z0-9]+-[A-Z0-9_]+)\s+(0x[0-9a-f]{8})\s+"
    r"(U1|U2|U4|U8|I1|I2|I4|I8|L|E1|E2|E4|X1|X2|X4|X8|R4|R8)\b"
)


def doc_text(name: str) -> str:
    pdf = ROOT / "refs/u-blox" / name
    return subprocess.run(["pdftotext", str(pdf), "-"], check=True, capture_output=True, text=True).stdout


def label(name: str) -> tuple[str, str]:
    """(group, label) of a CFG-MSGOUT message name, e.g. UBX_RXM_RAWX."""
    if name.startswith("UBX_"):
        _, cls, msg = name.split("_", 2)
        return f"UBX {cls}", f"UBX {cls}-{msg}"
    if name.startswith("NMEA_NAV2_ID_"):
        return "NMEA (NAV2)", f"NMEA NAV2 {name[len('NMEA_NAV2_ID_'):]}"
    if name.startswith("NMEA_ID_"):
        return "NMEA", f"NMEA {name[len('NMEA_ID_'):]}"
    if name.startswith("PUBX_ID_"):
        return "PUBX", f"PUBX {name[len('PUBX_ID_'):]}"
    if name.startswith("RTCM_3X_TYPE"):
        return "RTCM3", f"RTCM3 {name[len('RTCM_3X_TYPE'):]}"
    return "Other", name


def catalog(text: str) -> tuple[list[tuple[str, str, str, dict[str, int]]], dict[str, tuple[int, str]]]:
    items: dict[str, tuple[int, str]] = {}
    for m in ITEM.finditer(text):
        items.setdefault(m[1], (int(m[2], 16), m[3]))
    bases: dict[str, int] = {}
    for name, (key, _) in items.items():
        if not name.startswith("CFG-MSGOUT-"):
            continue
        rest = name[len("CFG-MSGOUT-"):]
        msg, _, port = rest.rpartition("_")
        if port in PORT_OFFSET:
            bases.setdefault(msg, key - PORT_OFFSET[port])
        elif rest.endswith("_"):  # port name cut off: the first key listed is I2C
            bases.setdefault(rest[:-1], key)
    messages = []
    for msg, base in sorted(bases.items(), key=lambda kv: label(kv[0])):
        # The ports listed by name; a message whose names were all cut has
        # every port.
        listed = {p for p in PORT_OFFSET if f"CFG-MSGOUT-{msg}_{p}" in items}
        ports = {p: base + off for p, off in PORT_OFFSET.items() if p in listed or not listed}
        group, text_label = label(msg)
        messages.append((msg, group, text_label, ports))
    other = {n: v for n, v in items.items() if n.split("-")[1] in OTHER_GROUPS}
    return messages, other


def main() -> int:
    lines = [
        "/**",
        " * u-blox configuration items (#136) of the ZED-F9P (F9 HPG 1.51) and NEO-D9C",
        " * (D9 QZS 1.01) Interface Descriptions: message output rate keys per port",
        " * (CFG-MSGOUT) and the items the Receiver tab reads and presets set.",
        " * Generated by scripts/gen_ublox_catalog.py; regenerate rather than edit.",
        " */",
        "",
        "export type UbloxModel = 'ZED-F9P' | 'NEO-D9C';",
        "export type UbloxPort = 'USB' | 'UART1' | 'UART2' | 'I2C' | 'SPI';",
        "",
        "export interface UbloxMessage {",
        "  /** CFG-MSGOUT item name, e.g. UBX_RXM_RAWX. */",
        "  name: string;",
        "  group: string;",
        "  label: string;",
        "  /** Output rate key ID per port. */",
        "  keys: Partial<Record<UbloxPort, number>>;",
        "}",
        "",
        "export interface UbloxModelCatalog {",
        "  messages: UbloxMessage[];",
        "  /** Other items by name: key ID and type (U1, L, E1, I1, ...). */",
        "  items: Record<string, [number, string]>;",
        "}",
        "",
        "export const UBLOX_CATALOG: Record<UbloxModel, UbloxModelCatalog> = {",
    ]
    for model, pdf in DOCS.items():
        messages, other = catalog(doc_text(pdf))
        lines.append(f"  '{model}': {{")
        lines.append("    messages: [")
        for msg, group, text_label, ports in messages:
            keys = ", ".join(f"{p}: 0x{ports[p]:08x}" for p in PORT_OFFSET if p in ports)
            lines.append(f"      {{ name: '{msg}', group: '{group}', label: '{text_label}', keys: {{ {keys} }} }},")
        lines.append("    ],")
        lines.append("    items: {")
        for name, (key, typ) in sorted(other.items()):
            lines.append(f"      '{name}': [0x{key:08x}, '{typ}'],")
        lines.append("    },")
        lines.append("  },")
        print(f"{model}: {len(messages)} messages, {len(other)} other items")
    lines += [
        "};",
        "",
        "/** UBX messages MRTKLIB's u-blox decoder reads (src/data/rcv/mrtk_rcv_ublox.c). */",
        "export const MRTKLIB_UBX_MESSAGES = new Set(['UBX_RXM_RAWX', 'UBX_RXM_SFRBX', 'UBX_RXM_QZSSL6']);",
        "",
    ]
    OUT.write_text("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
