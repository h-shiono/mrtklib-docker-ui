"""Regenerate frontend/src/utils/sbfCatalog.ts from the Septentrio Reference Guides.

    uv run python scripts/gen_sbf_catalog.py

Needs `pdftotext` (poppler) and the guides in refs/septentrio/ (not in the
repository). Reads the setSBFOutput group table and the block names of each
mosaic model; block names are checked against
services/stream_decoders/names.py, so prose such as "Serial Number:" is
not taken for a block.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GUIDES = {
    "mosaic-G5": "mosaic-G5 Firmware v1.1.0 Reference Guide.pdf",
    "mosaic-X5": "mosaic-X5 Firmware v4.16.0 Reference Guide.pdf",
    "mosaic-CLAS": "mosaic-CLAS Firmware v4.15.1 Reference Guide.pdf",
}
COMPOSITE = ("Support", "PostProcess", "Rinex", "RinexMeas3")
OUT = ROOT / "frontend/src/utils/sbfCatalog.ts"


def guide_text(name: str) -> str:
    pdf = ROOT / "refs/septentrio" / name
    return subprocess.run(["pdftotext", str(pdf), "-"], check=True, capture_output=True, text=True).stdout


def groups_of(text: str) -> dict[str, list[str]]:
    lines = [line.strip() for line in text.splitlines()]
    start = next(k for k, line in enumerate(lines) if line == "setSBFOutput")
    first = next(k for k in range(start, len(lines)) if lines[k].startswith("Predeﬁned groups of SBF blocks"))
    groups: dict[str, list[str]] = {}
    current = None
    for line in lines[first : first + 600]:
        if line.startswith("Example") or line.startswith("COM1>"):
            break
        if re.fullmatch(r"[A-Z][A-Za-z0-9]+", line) and line not in ("Messages", "Description"):
            current = line
            groups[current] = []
        elif line.startswith("+") and current:
            groups[current] += [x.lstrip("+") for x in line.split() if x.startswith("+")]
    return groups


def ts_list(xs: list[str]) -> str:
    return "[" + ", ".join(f"'{x}'" for x in xs) + "]"


def main() -> int:
    names_py = (ROOT / "src/mrtklib_web_ui/services/stream_decoders/names.py").read_text()
    known = set(re.findall(r'\d{4}: "([A-Za-z0-9]+)"', names_py))
    out = [
        "/**",
        " * SBF output groups and blocks of each Septentrio mosaic model (#136), from",
        " * the setSBFOutput group table and the block list of the mosaic-X5 v4.16.0,",
        " * mosaic-CLAS v4.15.1 and mosaic-G5 v1.1.0 Firmware Reference Guides.",
        " * Generated by scripts/gen_sbf_catalog.py; regenerate rather than edit.",
        " *",
        " * `composite` groups (Support, PostProcess, Rinex, ...) list every block",
        " * they contain; `groups` are the receiver's other predefined groups;",
        " * `other` are blocks in no predefined group (the receiver accepts them by",
        " * name).",
        " */",
        "",
        "export interface SbfModelCatalog {",
        "  composite: Record<string, string[]>;",
        "  groups: Record<string, string[]>;",
        "  other: string[];",
        "}",
        "",
        "export const SBF_CATALOG: Record<string, SbfModelCatalog> = {",
    ]
    for model, pdf in GUIDES.items():
        text = guide_text(pdf)
        groups = groups_of(text)
        blocks = sorted(set(re.findall(r"^([A-Z][A-Za-z0-9]+) Number:", text, re.M)) & known)
        grouped = {b for k, v in groups.items() if k not in COMPOSITE for b in v}
        out.append(f"  '{model}': {{")
        out.append("    composite: {")
        out += [f"      {k}: {ts_list(groups[k])}," for k in COMPOSITE if k in groups]
        out.append("    },")
        out.append("    groups: {")
        out += [f"      {k}: {ts_list(v)}," for k, v in groups.items() if k not in COMPOSITE]
        out.append("    },")
        out.append(f"    other: {ts_list([b for b in blocks if b not in grouped])},")
        out.append("  },")
    out += [
        "};",
        "",
        "/** Blocks MRTKLIB's SBF decoder reads (src/data/rcv/mrtk_rcv_septentrio.c). */",
        "export const MRTKLIB_SBF_BLOCKS = new Set([",
        "  'MeasEpoch', 'MeasExtra', 'GPSRawCA', 'GLORawCA', 'GALRawFNAV', 'GALRawINAV', 'GALRawCNAV',",
        "  'GEORawL1', 'GEORawL5', 'BDSRaw', 'BDSRawB2b', 'QZSRawL1CA', 'QZSRawL6', 'QZSRawL6D',",
        "  'QZSRawL6E', 'NAVICRaw', 'GPSNav', 'GLONav', 'GALNav', 'BDSCNav1', 'BDSNav', 'QZSNav',",
        "  'PVTGeodetic',",
        "]);",
        "",
    ]
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
